#!/usr/bin/env python3
"""Generate src/masonassist_description/worlds/terrain_test.world.

Ramp lanes along +x, one per (slope, surface): 4 m up at the slope angle,
a 3 m plateau, 4 m down. Surfaces differ only in friction coefficient.
A 10 deg side-slope lane, and the open ground at y = 0 for level tests.
Header (physics, plugins, scene, ground) is copied from
construction_site.world so the same world name and bridges work.
"""
import math
import os

WS = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
WORLDS = os.path.join(WS, 'src', 'masonassist_description', 'worlds')
RAMP_LEN, PLATEAU, WIDTH, THICK, X0 = 4.0, 3.0, 2.0, 0.2, 0.0
LANE_SPACING = 4.0
SURFACES = {'concrete': (1.0, (0.62, 0.6, 0.56)), 'gravel': (0.6, (0.5, 0.47, 0.42)),
            'clay': (0.4, (0.45, 0.33, 0.22))}
# (surface, slope deg), in lane order from y = 4
LANES = [('concrete', 10), ('concrete', 20), ('concrete', 30), ('concrete', 35),
         ('gravel', 10), ('gravel', 20), ('gravel', 30), ('clay', 10), ('clay', 20)]
CROSS_SLOPE_DEG = 10


def lane_y(i):
    return LANE_SPACING * (i + 1)


def cross_slope_y():
    return LANE_SPACING * (len(LANES) + 1)


def _box(name, x, y, z, roll, pitch, size, surface, comment=''):
    mu, rgb = SURFACES[surface]
    geom = f'<geometry><box><size>{size[0]:.4f} {size[1]:.4f} {size[2]:.4f}</size></box></geometry>'
    mat = f'<material><ambient>{rgb[0]} {rgb[1]} {rgb[2]} 1</ambient><diffuse>{rgb[0]} {rgb[1]} {rgb[2]} 1</diffuse></material>'
    fric = f'<surface><friction><ode><mu>{mu}</mu><mu2>{mu}</mu2></ode></friction></surface>'
    return (f'    <model name="{name}"><static>true</static>'
            f'<pose>{x:.4f} {y:.4f} {z:.4f} {roll:.6f} {pitch:.6f} 0</pose>{comment}\n'
            f'      <link name="link"><collision name="c">{geom}{fric}</collision>'
            f'<visual name="v">{geom}{mat}</visual></link></model>\n')


def build():
    src = open(os.path.join(WORLDS, 'construction_site.world')).read().splitlines(keepends=True)
    end = next(i for i, line in enumerate(src) if '<model name="ground_plane">' in line)
    end = next(i for i in range(end, len(src)) if '</model>' in src[i]) + 1
    header = ''.join(src[:end]).replace(
        '<world name="masonassist_world">',
        '<world name="masonassist_world">\n    <!-- Generated by tools/make_terrain_world.py for tools/terrain_test.py -->', 1)
    out = [header, '\n    <!-- Ramp lanes: 4 m up at the slope angle, 3 m plateau, 4 m down -->\n']
    for i, (surface, deg) in enumerate(LANES):
        y, th = lane_y(i), math.radians(deg)
        run, h, s, c = RAMP_LEN * math.cos(th), RAMP_LEN * math.sin(th), math.sin(th), math.cos(th)
        key = f'{surface}_{deg}'
        out.append(_box(f'ramp_up_{key}', X0 + run / 2 + THICK / 2 * s, y, h / 2 - THICK / 2 * c, 0, -th,
                        (RAMP_LEN, WIDTH, THICK), surface, f' <!-- {deg} deg {surface}, rise {h:.2f} m -->'))
        out.append(_box(f'plateau_{key}', X0 + run + PLATEAU / 2, y, h / 2, 0, 0, (PLATEAU, WIDTH, h), surface))
        x1 = X0 + run + PLATEAU
        out.append(_box(f'ramp_down_{key}', x1 + run / 2 - THICK / 2 * s, y, h / 2 - THICK / 2 * c, 0, th,
                        (RAMP_LEN, WIDTH, THICK), surface))
    th, w = math.radians(CROSS_SLOPE_DEG), 3.0
    y0 = cross_slope_y()
    out.append(f'\n    <!-- Side slope: {CROSS_SLOPE_DEG} deg roll, low edge on the ground at y = {y0} -->\n')
    out.append(_box(f'cross_slope_{CROSS_SLOPE_DEG}', 2.0, y0 + w / 2 * math.cos(th),
                    w / 2 * math.sin(th) - THICK / 2 * math.cos(th), th, 0, (10.0, w, THICK), 'concrete'))
    out.append('  </world>\n</sdf>\n')
    path = os.path.join(WORLDS, 'terrain_test.world')
    open(path, 'w').write(''.join(out))
    write_site_config()
    return path


NO_GO_MIN_DEG = 30          # ramps this steep or steeper are no-go when loaded
NO_GO_MAX_PAYLOAD_KG = 25   # above this (50 kg tested) the robot tipped over them


def write_site_config():
    """config/terrain_site.yaml: no-go zones over every ramp >= NO_GO_MIN_DEG
    (both the climb and the descent), for the tilt/zone guard tests."""
    lines = ['# Generated by tools/make_terrain_world.py - no-go zones for worlds/terrain_test.world',
             f'# Every ramp of {NO_GO_MIN_DEG} deg or more, for robots carrying more than '
             f'{NO_GO_MAX_PAYLOAD_KG} kg (docs/terrain).', 'no_go_zones:']
    for i, (surface, deg) in enumerate(LANES):
        if deg < NO_GO_MIN_DEG:
            continue
        y, th = lane_y(i), math.radians(deg)
        run = RAMP_LEN * math.cos(th)
        x1 = X0 + run + PLATEAU
        for name, x0 in (('up', X0), ('down', x1)):
            lines.append(f'  {surface}_{deg}_{name}: {{box: [{x0 + run / 2:.3f}, {y}, {run / 2:.3f}, {WIDTH / 2}], '
                         f'max_payload_kg: {NO_GO_MAX_PAYLOAD_KG}, reason: "{deg} deg {surface} ramp"}}')
    path = os.path.join(os.path.dirname(WORLDS), 'config', 'terrain_site.yaml')
    open(path, 'w').write('\n'.join(lines) + '\n')
    return path


if __name__ == '__main__':
    print(build())
